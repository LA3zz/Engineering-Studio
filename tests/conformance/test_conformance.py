"""Conformance suite for the interpreter (ARCHITECTURE section 11).

Every ``cases/NN_name.m`` runs through the real in-process kernel (all builtins, command
syntax) and its output must equal ``cases/NN_name.expected`` exactly. The expected files were
derived by hand from MATLAB semantics (plus the documented differences), never generated by
this interpreter. Scripts print with ``fprintf``/``disp`` so the check does not depend on the
display format. A failing case means an interpreter bug or a wrong expectation: investigate
before touching either.
"""

from pathlib import Path

import pytest

from engstudio.app.kernel.inprocess import InProcessKernelClient
from engstudio.app.kernel.protocol import Diagnostics, ExecutionFinished, Stdout

CASES = sorted((Path(__file__).parent / "cases").glob("*.m"))


def run_case(path: Path) -> tuple[str, list[str], list[str]]:
    out: list[str] = []
    errors: list[str] = []
    status: list[str] = []

    def on_event(event: object) -> None:
        if isinstance(event, Stdout):
            out.append(event.text)
        elif isinstance(event, Diagnostics):
            errors.extend(d.message for d in event.items if d.severity == "error")
        elif isinstance(event, ExecutionFinished):
            status.append(str(getattr(event, "status", "")))

    client = InProcessKernelClient(threaded=False)
    client.subscribe(on_event)
    try:
        client.execute(path.read_text(encoding="utf-8"), str(path))
    finally:
        client.shutdown()
    return "".join(out), errors, status


def test_cases_exist():
    assert len(CASES) >= 12


@pytest.mark.parametrize("path", CASES, ids=lambda p: p.stem)
def test_case(path):
    output, errors, status = run_case(path)
    assert not errors, f"{path.name}: unexpected errors: {errors}"
    assert status == ["ok"], f"{path.name}: finished with {status}"
    expected = path.with_suffix(".expected").read_text(encoding="utf-8").replace("\r\n", "\n")
    assert output.replace("\r\n", "\n") == expected
